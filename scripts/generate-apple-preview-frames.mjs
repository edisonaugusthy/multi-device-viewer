// Rebuild simulator artwork and its live-screen paths together. These are
// presentation frames, not manufacturer photographs or native measurements.
import { readFile, writeFile } from 'node:fs/promises';

const models = [
  { id: 'apple-iphone-18-pro-2026', width: 402, height: 874, corners: [76,76,76,76], color: ['#39232b','#a36e80','#e1bdc9'], camera: { x: 153, y: 14, width: 96, height: 36, radius: 18 } },
  { id: 'apple-iphone-18-pro-max-2026', width: 440, height: 956, corners: [84,84,84,84], color: ['#172d3a','#557f98','#b3d0e0'], camera: { x: 172, y: 14, width: 96, height: 36, radius: 18 } },
  { id: 'apple-iphone-duo-folded-2026', width: 466, height: 678, corners: [10,68,68,10], color: ['#292a29','#7b7d78','#d1d2ca'], folded: true, camera: { x: 400, y: 35, width: 36, height: 36, radius: 18 } },
  { id: 'apple-iphone-duo-unfolded-2026', width: 890, height: 626, corners: [58,58,58,58], color: ['#292a29','#7b7d78','#d1d2ca'], unfolded: true },
];
const n = v => Number(v.toFixed(4));
function outline(x, y, w, h, corners) {
  const [a,b,c,d] = corners, r=x+w, bottom=y+h, k=.38;
  return `M${x+a} ${y}H${r-b}C${r-b*k} ${y} ${r} ${y+b*k} ${r} ${y+b}V${bottom-c}C${r} ${bottom-c*k} ${r-c*k} ${bottom} ${r-c} ${bottom}H${x+d}C${x+d*k} ${bottom} ${x} ${bottom-d*k} ${x} ${bottom-d}V${y+a}C${x} ${y+a*k} ${x+a*k} ${y} ${x+a} ${y}Z`;
}
function cameraPath({x,y,width:w,height:h,radius:r}) {
  return `M${x+r} ${y}H${x+w-r}A${r} ${r} 0 0 1 ${x+w} ${y+r}V${y+h-r}A${r} ${r} 0 0 1 ${x+w-r} ${y+h}H${x+r}A${r} ${r} 0 0 1 ${x} ${y+h-r}V${y+r}A${r} ${r} 0 0 1 ${x+r} ${y}Z`;
}
function rotateCamera(c,h) {
  return c && { x:h-c.y-c.height, y:c.x, width:c.height, height:c.width, radius:c.radius };
}
function viewport(width,height,corners,camera,left,top,orientation) {
  return { left,top,width,height,cornerRadius:Math.max(...corners),enableRotation:true,
    paths:{[orientation]:outline(0,0,width,height,corners)+(camera?cameraPath(camera):'')} };
}
const catalogPath = new URL('../src/domain/device/mockup-catalog.ts', import.meta.url);
let catalog = await readFile(catalogPath, 'utf8');
for (const model of models) {
  const {id,width:w,height:h,corners,color:[dark,mid,light],camera}=model;
  const insetX=18,insetY=16,W=w+insetX*2,H=h+insetY*2;
  const layer=(inset,fill,stroke='',strokeWidth=1)=>`<path d="${outline(inset,inset,W-inset*2,H-inset*2,corners.map(r=>r+16-inset))}" fill="${fill}"${stroke?` stroke="${stroke}" stroke-width="${strokeWidth}"`:''}/>`;
  const button=(x,y,width,height)=>`<rect x="${x}" y="${y}" width="${width}" height="${height}" rx="1.6" fill="url(#rail)" stroke="${dark}" stroke-width=".6"/>`;
  let buttons;
  if(model.unfolded) buttons=button(n(W*.7),0,54,5)+button(n(W*.78),0,32,5);
  else if(model.folded) buttons=button(W-5,150,4,50)+button(W-5,220,4,75);
  else buttons=button(1,122,4,26)+button(1,184,4,60)+button(1,262,4,60)+button(W-5,244,4,92)+button(W-5,458,4,44);
  // An opaque black face backs the clipped page. Cutting a second transparent
  // aperture here would double-antialias its edge into a visible pale hairline.
  const lens=camera?`<g transform="translate(${insetX+camera.x} ${insetY+camera.y})"><rect width="${camera.width}" height="${camera.height}" rx="${camera.radius}" fill="#030405"/><circle cx="${camera.width-camera.height/2}" cy="${camera.height/2}" r="6.5" fill="#080d16"/><circle cx="${camera.width-camera.height/2}" cy="${camera.height/2}" r="3" fill="#101a2d"/><circle cx="${camera.width-camera.height/2-1}" cy="${camera.height/2-1}" r="1" fill="#283a59"/></g>`:'';
  const hinge=model.folded?`<path d="M7 42V${H-42}" stroke="${light}" stroke-opacity=".25" stroke-width="1"/>`:model.unfolded?`<path d="M${W/2} 2v5m0 ${H-14}v5" stroke="${dark}" stroke-width="2"/>`:'';
  const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
<!-- Generated by scripts/generate-apple-preview-frames.mjs. Simulator artwork. -->
<defs>
  <linearGradient id="rail" x1="0" y1="0" x2="1" y2="0" gradientUnits="objectBoundingBox"><stop stop-color="${dark}"/><stop offset=".16" stop-color="${mid}"/><stop offset=".42" stop-color="${light}"/><stop offset=".64" stop-color="${mid}"/><stop offset="1" stop-color="${dark}"/></linearGradient>
  <linearGradient id="face" x1="0" y1="0" x2="1" y2="1"><stop stop-color="${mid}"/><stop offset=".28" stop-color="${dark}"/><stop offset=".56" stop-color="${mid}"/><stop offset=".78" stop-color="${dark}"/><stop offset="1" stop-color="${mid}"/></linearGradient>
</defs>
${buttons}
${layer(4,'url(#rail)',dark)}
${layer(5.5,'url(#face)',light,.6)}
${layer(9,'#08090b',dark,1.5)}
${layer(11,'#030405')}
${hinge}
${lens}
</svg>
`;
  await writeFile(new URL(`../public/mockups/${id}.svg`,import.meta.url),svg);
  const start=catalog.indexOf('{\n  "id": "'+id+'"');
  if(start<0)throw new Error('Missing catalog entry: '+id);
  const end=catalog.indexOf('\n},',start)+2;
  const asset=JSON.parse(catalog.slice(start,end));
  // Remove photo provenance: generated chrome must not claim to be Apple art.
  delete asset.sourceUrl;
  delete asset.previewScale;
  Object.assign(asset,{bytes:Buffer.byteLength(svg),width:W,height:H,renderScale:1,frameOverlay:false,
    screenInset:{left:insetX,top:insetY,right:insetX,bottom:insetY}});
  const nativeOrientation=w>h?'landscape':'portrait';
  const rotatedOrientation=w>h?'portrait':'landscape';
  asset.viewport={
    [nativeOrientation]:viewport(w,h,corners,camera,insetX,insetY,nativeOrientation),
    [rotatedOrientation]:viewport(h,w,[corners[3],corners[0],corners[1],corners[2]],rotateCamera(camera,h),insetY,insetX,rotatedOrientation),
  };
  catalog=catalog.slice(0,start)+JSON.stringify(asset,null,2)+catalog.slice(end);
}
await writeFile(catalogPath,catalog);
console.log('Generated four Apple preview frames and matching screen paths.');
