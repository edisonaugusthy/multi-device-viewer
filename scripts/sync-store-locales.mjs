import { readFile, writeFile, mkdir } from "node:fs/promises";
const { locales } = JSON.parse(await readFile("store-assets/listings/locales.json", "utf8"));
const check = process.argv.includes("--check");
const failures = [];
async function output(path, content) {
  if (check) { if (await readFile(path, "utf8").catch(() => "") !== content) failures.push(`${path}: stale generated content`); }
  else await writeFile(path, content);
}
let markdown = "# Localized Chrome Web Store listing copy\n\nGenerated by `npm run sync:store-locales` from `store-assets/listings/locales.json`.\nCopy each record into its matching store language. Packaging extension messages does not publish store descriptions.\n\n";
const signatures = new Map();
if (locales.length !== 55) throw new Error("Expected 55 locale records.");
for (const record of locales) {
  const { locale, language, name, summary, description, screenshotCaptions, storeLocale } = record;
  if ([...name].length > 75 || [...summary].length > 132 || description.length > 16000 || !description.trim()) failures.push(`${locale}: invalid field length`);
  const prior = signatures.get(description);
  if (prior && !locale.startsWith("en") && locale !== "es_419") failures.push(`${locale}: duplicated description from ${prior}`);
  signatures.set(description, locale);
  const metadataPath = `public/_locales/${locale}/messages.json`;
  const messages = JSON.parse(await readFile(metadataPath, "utf8"));
  messages.extensionName.message = name; messages.extensionDescription.message = summary;
  await output(metadataPath, JSON.stringify(messages, null, 2) + "\n");
  markdown += `## \`${locale}\` — ${language}\n\n**Store locale:** ${storeLocale}\n\n**Name:** ${name}\n\n**Summary:** ${summary}\n\n**Detailed description**\n\n${description}\n\n**Screenshot captions**\n\n${screenshotCaptions.map((v,i) => `${i+1}. ${v}`).join("\n")}\n\n`;
  const directory = `store-assets/listings/upload/${locale}`;
  if (!check) await mkdir(directory, { recursive: true });
  await output(`${directory}/description.txt`, description + "\n");
  await output(`${directory}/metadata.json`, JSON.stringify({ storeLocale, name, summary, screenshotCaptions, screenshotLocale: record.screenshotLocale }, null, 2) + "\n");
}
const captionLocales = new Set(locales.map(record => record.screenshotLocale));
const captions = Object.fromEntries(locales.filter(record => captionLocales.has(record.locale)).map(record => [record.locale, record.screenshotCaptions]));
await output('store-assets/listings/captions.js', `// Generated from locales.json by sync:store-locales.\nwindow.MDV_STORE_CAPTIONS = ${JSON.stringify(captions, null, 2)};\n`);
await output("docs/chrome-web-store-listing-copy.md", markdown.trimEnd() + "\n");
if (failures.length) throw new Error(failures.join("\n"));
console.log(`${check ? "Validated" : "Generated"} ${locales.length} store locales, package messages and upload records.`);
